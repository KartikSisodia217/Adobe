import asyncio
import time
from src.orchestration.orchestrator import execute_audit

# Example Ground Truth for benchmarking (Expected Detector IDs)
GROUND_TRUTH = {
    "https://example.com": {"expected_detectors": []},
    "https://mock-defective-site.com/": {"expected_detectors": ["D-01", "E-01"]}
}

async def run_benchmark():
    print("Starting AIMLESS Benchmark Harness...")
    results = []
    
    total_start = time.time()
    for url, truth in GROUND_TRUTH.items():
        print(f"Auditing {url}...")
        try:
            report = await execute_audit(url)
            # Use detector_id or title to map back. The title is generated by cap.py: title=f"{f.mechanism.capitalize()}"
            # Actually, `id` in report is "F-001" etc., but let's check `evidence_items` or we can just infer by mechanism title.
            # To be robust, let's map report mechanism titles to roughly expected IDs.
            # E.g. "Robots.txt" -> "D-01", "Rendering gap" -> "E-01"
            title_to_id = {
                "Robots.txt": "D-01",
                "Rendering gap": "E-01",
                "Schema validation": "D-02",
                "Modal focus trap": "G-02",
                "Primary-route-unreachable": "G-03"
            }
            
            actual_detectors = []
            for f in report.get("findings", []):
                mapped_id = title_to_id.get(f["title"], "UNKNOWN")
                actual_detectors.append(mapped_id)
                
            expected = set(truth["expected_detectors"])
            actual = set(actual_detectors)
            
            tp = len(expected.intersection(actual))
            fp = len(actual - expected)
            fn = len(expected - actual)
            
            results.append({
                "url": url,
                "runtime_ms": report.get("coverage", {}).get("runtime_ms", 0),
                "tp": tp,
                "fp": fp,
                "fn": fn
            })
        except Exception as e:
            print(f"Error auditing {url}: {e}")
            
    total_time = time.time() - total_start
    
    total_tp = sum(r["tp"] for r in results)
    total_fp = sum(r["fp"] for r in results)
    total_fn = sum(r["fn"] for r in results)
    
    precision = total_tp / (total_tp + total_fp) if (total_tp + total_fp) > 0 else 0.0
    recall = total_tp / (total_tp + total_fn) if (total_tp + total_fn) > 0 else 0.0
    f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
    
    print("\n--- Benchmark Results ---")
    print(f"Total Sites: {len(results)}")
    print(f"True Positives: {total_tp}")
    print(f"False Positives: {total_fp}")
    print(f"False Negatives: {total_fn}")
    print(f"Precision: {precision*100:.1f}%")
    print(f"Recall: {recall*100:.1f}%")
    print(f"F1 Score: {f1*100:.1f}%")
    print(f"Total Runtime: {total_time:.2f}s")
    print("-------------------------\n")

if __name__ == "__main__":
    asyncio.run(run_benchmark())
